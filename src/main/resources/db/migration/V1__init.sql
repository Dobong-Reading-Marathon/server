-- 회차 (연도별 대회)
CREATE TABLE rounds (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_no    INTEGER NOT NULL,
    year        INTEGER NOT NULL,
    start_date  DATE    NOT NULL,
    end_date    DATE    NOT NULL,
    apply_start DATE,
    apply_end   DATE,
    UNIQUE (year, round_no)                            -- 1년에 회차가 여러 번일 수 있지만, 같은 연도에 같은 회차 번호는 하나
);

-- 회차별 코스와 완주 기준
CREATE TABLE courses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_id       BIGINT      NOT NULL REFERENCES rounds (id),
    name           VARCHAR(50) NOT NULL,
    is_family      BOOLEAN     NOT NULL DEFAULT FALSE,
    target_pages   INTEGER     NOT NULL,
    target_reviews INTEGER     NOT NULL,
    target_books   INTEGER     NOT NULL,
    sort_order     INTEGER     NOT NULL DEFAULT 0
);

-- 참가자 회원
CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(50)  NOT NULL,
    phone                VARCHAR(20)  NOT NULL UNIQUE, -- 전화번호로 로그인, 중복 가입 방지 (F-0101, F-0102)
    password_hash        VARCHAR(255) NOT NULL,
    loan_member_no       VARCHAR(30),
    privacy_agreed_at    TIMESTAMPTZ  NOT NULL,
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- 관리자(사서)
CREATE TABLE admins (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    name          VARCHAR(50)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- 도서 정보
CREATE TABLE books (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn         VARCHAR(13) UNIQUE, -- 책 정보는 전체 회차에서 하나. ISBN13을 하이픈 없이 저장
    title        VARCHAR(255) NOT NULL,
    author       VARCHAR(255) NOT NULL,
    publisher    VARCHAR(100),
    publish_year INTEGER,
    total_pages  INTEGER      NOT NULL,
    cover_url    VARCHAR(500),
    is_children  BOOLEAN      NOT NULL DEFAULT FALSE,
    source       VARCHAR(10)  NOT NULL DEFAULT 'MANUAL',
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- 회차 참가 신청
CREATE TABLE enrollments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT      NOT NULL REFERENCES users (id),
    round_id            BIGINT      NOT NULL REFERENCES rounds (id),
    course_id           BIGINT      NOT NULL REFERENCES courses (id),
    status              VARCHAR(20) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE / COMPLETED
    verified_loan_count INTEGER,
    approval_note       VARCHAR(255),
    approved_by         BIGINT REFERENCES admins (id),
    approved_at         TIMESTAMPTZ,
    certificate_no      VARCHAR(30) UNIQUE,            -- 인증서 번호는 중복될 수 없음 (F-0803)
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, round_id)                         -- 같은 회차 중복 신청 방지 (F-0205)
);

-- 참가자가 등록한 책 (내서재)
CREATE TABLE enrollment_books (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id    BIGINT      NOT NULL REFERENCES enrollments (id),
    book_id          BIGINT      NOT NULL REFERENCES books (id),
    is_library_owned BOOLEAN     NOT NULL DEFAULT FALSE,
    registration_no  VARCHAR(30),
    loan_date        DATE,
    return_date      DATE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (enrollment_id, book_id)                    -- 한 회차 참가에 같은 책은 한 번만 등록
);

-- 독서기록 (쪽 범위, 글귀, 서평, 심사 상태)
CREATE TABLE reading_logs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_book_id BIGINT      NOT NULL REFERENCES enrollment_books (id),
    start_page         INTEGER     NOT NULL,
    end_page           INTEGER     NOT NULL,
    read_date          DATE        NOT NULL,
    quote              TEXT,
    review             TEXT,
    status             VARCHAR(20) NOT NULL DEFAULT 'DRAFT', -- DRAFT / SUBMITTED / APPROVED / REVISION_REQUESTED
    submitted_at       TIMESTAMPTZ,
    reviewed_by        BIGINT REFERENCES admins (id),
    reviewed_at        TIMESTAMPTZ,
    librarian_comment  TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (start_page >= 1 AND start_page <= end_page) -- 시작 쪽 <= 끝 쪽 (완주 기준 문서)
);
