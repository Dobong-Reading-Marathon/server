-- V3: 로그인 세션 (F-0102)
--
-- 로그인하면 서버가 무작위 토큰을 만들어 응답으로 한 번만 돌려주고, DB에는 토큰의 SHA-256 해시만 저장합니다.
-- DB가 유출돼도 해시로는 로그인할 수 없습니다.
-- 로그아웃하면 행을 지워서 토큰을 바로 무효로 만듭니다 (JWT와 달리 서버에서 즉시 취소 가능).
-- 관리자 세션(F-0104)은 이후 마이그레이션에서 추가합니다.

CREATE TABLE auth_sessions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash          VARCHAR(64) NOT NULL UNIQUE,                         -- SHA-256 hex. 원본 토큰은 저장하지 않음
    user_id             BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    remember_me         BOOLEAN     NOT NULL,                                -- 로그인 상태 유지 여부 (true면 사용할 때마다 만료 연장)
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at          TIMESTAMPTZ NOT NULL,                                -- 현재 만료 시각
    absolute_expires_at TIMESTAMPTZ NOT NULL                                 -- 연장해도 넘을 수 없는 최대 만료 시각
);

CREATE INDEX idx_auth_sessions_user_id ON auth_sessions (user_id);
CREATE INDEX idx_auth_sessions_expires_at ON auth_sessions (expires_at);   -- 만료 세션 정리용
