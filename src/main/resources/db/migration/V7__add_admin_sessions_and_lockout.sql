-- V7: 관리자 로그인 세션과 로그인 실패 잠금 (F-0104)
--
-- 참가자 세션(auth_sessions)과 테이블을 나눔. 서버는 /api/admin/ 주소일 때만 이 테이블을 조회함.
-- 그래서 참가자 토큰으로 관리자 API를, 관리자 토큰으로 참가자 API를 쓸 수 없음.
-- 토큰 원본은 저장하지 않고 SHA-256 해시만 저장. 로그아웃하면 행을 지워 즉시 무효.
-- 관리자 세션은 연장 없이 로그인 8시간 뒤 만료 (app.admin.session-max).

CREATE TABLE admin_sessions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,                           -- SHA-256 hex. 원본 토큰은 저장하지 않음
    admin_id   BIGINT      NOT NULL REFERENCES admins (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL                                   -- 만료 시각 (연장 없음)
);

CREATE INDEX idx_admin_sessions_admin_id ON admin_sessions (admin_id);
CREATE INDEX idx_admin_sessions_expires_at ON admin_sessions (expires_at);   -- 만료 세션 정리용

-- 참가자(V4)와 같은 방식. 연속으로 정해진 횟수 틀리면 locked_until까지 로그인을 막고, 성공하면 0으로 되돌림
ALTER TABLE admins
    ADD COLUMN failed_login_count INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN locked_until       TIMESTAMPTZ;
