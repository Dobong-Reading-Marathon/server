-- V8: 개인정보 처리방침 버전과 회원의 동의 버전 (F-0103)
--
-- 처리방침 문안은 회원마다 같으므로 버전별로 한 번만 저장하고, 회원은 동의한 버전 번호만 가짐.
-- 현재 버전 = 시행일이 오늘(한국 날짜) 이전인 버전 중 가장 큰 번호.
-- 문안 변경은 새 마이그레이션으로만 함. 이 파일은 이미 실행된 뒤 고치면 Flyway가 서버 시작을 막음.
--
-- 2~4절은 도서관에서 받을 문안 자리 ([도서관 제공 문안]). 운영(prod)에서는 이 글자가 남아 있으면 서버가 시작되지 않음.

CREATE TABLE privacy_policies (
    version        INTEGER     PRIMARY KEY,
    effective_from DATE        NOT NULL,                 -- 시행일
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 처리방침의 절 (제목 + 본문). 본문은 일반 텍스트이고 줄바꿈만 있음 (HTML 아님)
CREATE TABLE privacy_policy_sections (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version    INTEGER      NOT NULL REFERENCES privacy_policies (version),
    sort_order INTEGER      NOT NULL,
    title      VARCHAR(100) NOT NULL,
    body       TEXT         NOT NULL,
    UNIQUE (version, sort_order)
);

